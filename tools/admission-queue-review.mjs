#!/usr/bin/env node
/**
 * Review the relay's admission queue as the operator, and separate TRIAL DEBRIS from a REAL
 * APPLICANT -- because on 2026-10-12 those were indistinguishable, and 16 trial entries were
 * sitting in front of a human who had no way to tell them apart.
 *
 * WHY THIS MATTERS. The console's admission review is the human admin's job: look at who is
 * waiting, decide. It is not usable if the queue is full of the test harness's own leavings and
 * nothing marks them as such. The failure is asymmetric and that is the whole design principle
 * here: showing a trial entry as a possible applicant costs a human ten seconds of reading, while
 * showing a REAL applicant as trial debris means the applicant is silently never admitted. So the
 * classifier fails toward the human, never away from them.
 *
 * THE CONVENTION, going forward: a request generated by a trial MUST carry a note beginning
 * `[trial]`. The legacy labels below predate the convention and are listed explicitly so the
 * existing debris stays recognisable. Anything else -- including an empty note -- is REAL, i.e.
 * "a human should look at this".
 *
 * THE KNOWN LIMIT, stated rather than glossed: a real applicant who sets their note to exactly
 * "joiner-path-trial" would be misclassified as debris. That is a deliberate trade: the legacy
 * list is fixed and documented, the strings are meaningless outside this repository, and the
 * alternative (guessing) is worse.
 *
 * COMPLETENESS IS NOT ASSUMED, it is read. The relay reports whether the page it sent was the whole
 * queue (`truncated`, from the KV binding's own list_complete) and which entries existed but could
 * not be read (`unreadable`). Either one means the human has NOT seen everyone who is waiting, so
 * this tool exits 2 instead of printing "no real applicants waiting" over an entrant it never saw.
 * A relay that reports neither is an older deployment: that is printed as a stated limit and does
 * not fail a review that did read everything it was given.
 *
 * Usage:
 *   node tools/admission-queue-review.mjs                 # human-readable
 *   node tools/admission-queue-review.mjs --json
 * Exit: 0 = reviewed, 2 = COULD NOT REVIEW (never report an unreachable queue as an empty one).
 */

import { readFileSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const RELAY = process.env.COMMONS_URL || 'https://agent-commons.huyxkhoa.workers.dev';
const SECRET_FILE = process.env.AC_OPERATOR_SECRET_FILE
  || join(homedir(), '.dsh', 'agent-commons', 'relay-operator-secret.txt');

// The classifier now lives in src/ so that the CONSOLE applies the same judgement as this tool.
// Two copies of one convention drift, and this drift is asymmetric: a real applicant mislabelled as
// debris is silently never admitted, while a debris entry shown as an applicant costs ten seconds of
// reading. `import` gives main() a local binding; the `export ... from` keeps this tool's public
// surface identical for its test.
import { triage } from '../src/queue-classify.mjs';
// The relay's answer is read by ONE reader, shared with the console. See src/queue-read.mjs.
import { readQueue } from '../src/queue-read.mjs';
export { LEGACY_TRIAL_NOTES, TRIAL, REAL, classifyNote, triage } from '../src/queue-classify.mjs';

function main() {
  const asJson = process.argv.includes('--json');
  if (!existsSync(SECRET_FILE)) {
    console.error(`admission queue review: FAIL — no operator secret at ${SECRET_FILE}`);
    console.error('  Without it this route answers 401, and an unauthorised read MUST NOT be');
    console.error('  reported as an empty queue.');
    process.exit(2);
  }
  const token = readFileSync(SECRET_FILE, 'utf8').trim();

  // Cache-buster: a stale edge copy of this route would report a queue that is not there.
  const url = `${RELAY}/admission/requests?cb=${Math.random().toString(36).slice(2)}`;
  return fetch(url, { headers: { authorization: `Bearer ${token}`, 'cache-control': 'no-store' } })
    .then(async (res) => {
      if (!res.ok) throw new Error(`operator route returned HTTP ${res.status}`);
      return res.json();
    })
    .then((body) => {
      // A 200 is not the same thing as a queue. The route always sends `requests` (worker.js builds
      // the array even when it is empty), so a body without one means we did NOT read the queue --
      // and rendering that as "no real applicants waiting" is the one wrong answer this tool exists
      // to prevent. Guard the SHAPE, not just the status code: the 401 arm below never sees this case.
      if (!Array.isArray(body?.requests)) {
        const what = body === null || body === undefined ? String(body)
          : 'requests' in body ? JSON.stringify(body.requests)?.slice(0, 60) ?? String(body.requests)
            : `no requests field (keys: ${Object.keys(body).join(',') || 'none'})`;
        throw new Error(`operator route returned a body that is not a queue: ${what}`);
      }
      // ONE reader for the relay's answer, shared with the console (src/queue-read.mjs). Two copies
      // of "what counts as a queue" would drift, and the drift is asymmetric: a queue read as empty
      // is a human never looking at the joiner who was in fact waiting.
      const view = readQueue(body);
      const { rows, trials, real } = view.read ? triage(view.rows) : { rows: [], trials: [], real: [] };
      // COMPLETENESS is a separate question from what the queue contains, and this tool must not
      // answer it by assumption. A relay that reports it can say the page was cut short, or that an
      // entry exists and could not be read; either way the human has NOT seen the whole queue, and
      // saying "no real applicants waiting" over that would be the one wrong answer again.
      // A relay that reports neither is an older deployment: that is a STATED LIMIT, not a finding,
      // so it is printed and does not fail a review that did read everything it was given.
      // `truncated` is read STRICTLY, through readQueue: a value present but not true/false is not
      // knowledge, so it can no longer license the words "page complete". The test this replaced
      // (`body.truncated !== undefined`) counted `truncated: "yes"` as a report of completeness.
      const truncated = view.truncated === true;
      const unreadable = view.unreadable;
      const partial = view.truncated === true || (Array.isArray(unreadable) && unreadable.length > 0);
      const completeness = view.truncated === null
        ? 'NOT REPORTED by this relay, so completeness cannot be confirmed from here'
        : `${rows.length} read; ${truncated ? 'MORE WAITING, the page was cut short' : 'page complete'}; ${unreadable === null ? 'unreadable count not reported' : `${unreadable.length} unreadable`}`;
      if (!view.read) {
        // A body with no requests list is not an empty queue, and this tool exists to keep those two
        // apart. Exit 2 = "could not review", never 0.
        console.error(`admission queue review: FAIL — ${view.why}`);
        console.error('  Reporting this as "no applicants waiting" would be the one wrong answer.');
        process.exit(2);
      }
      if (asJson) {
        console.log(JSON.stringify({
          relay: RELAY, total: rows.length, trials: trials.length, real: real.length,
          truncated, unreadable, completeness, caveats: view.caveats, rows,
        }, null, 2));
      } else {
        console.log(`admission queue at ${RELAY}`);
        console.log(`  waiting: ${rows.length}   trial debris: ${trials.length}   REAL APPLICANTS: ${real.length}`);
        console.log(`  completeness: ${completeness}`);
        // The stated limits are printed next to the count they qualify. A caveat that only exists in
        // the JSON is a caveat the human reading the screen never sees.
        for (const c of view.caveats) console.log(`  caveat: ${c}`);
        if (real.length) {
          console.log('');
          console.log('  --- these are not ours; a human should decide them ---');
          for (const r of real) {
            console.log(`    ${r.requestId}`);
            console.log(`      at:   ${new Date(r.at).toISOString()}`);
            console.log(`      note: ${r.note === null || r.note === undefined ? '(none)' : JSON.stringify(r.note)}`);
            console.log(`      why:  ${r.why}`);
          }
        } else {
          console.log('  (no real applicants waiting)');
        }
        if (trials.length) {
          console.log('');
          console.log('  trial debris, safe to clear:');
          for (const r of trials) console.log(`    ${r.requestId}  (${r.why})`);
        }
      }
      if (partial) {
        console.error('');
        console.error('admission queue review: INCOMPLETE — this was NOT the whole queue.');
        if (truncated) console.error('  the relay reported more waiting requests than this page carries (truncated: true)');
        if (unreadable?.length) {
          console.error(`  entries that exist but could not be read: ${unreadable.join(', ')}`);
        }
        console.error('  An entry left unread is an entry the human never decided, which is how a real applicant is binned.');
        process.exit(2);
      }
    })
    .catch((err) => {
      console.error(`admission queue review: FAIL — ${err.message}`);
      console.error('  Reporting this as "no applicants waiting" would be the one wrong answer.');
      process.exit(2);
    });
}

if (process.argv[1] && process.argv[1].endsWith('admission-queue-review.mjs')) main();
