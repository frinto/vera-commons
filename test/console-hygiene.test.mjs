// test/console-hygiene.test.mjs — pin the console-runner contract with REAL listeners and REAL children.
//
// WHY THIS EXISTS (measured 2026-10-12). Two console processes can hold the same port on Windows, so
// "my spawn did not throw" does not mean "my request reached MY console". That night a console started
// from a STALE copy of this project (E:\AgentCommons\app.mjs) held 127.0.0.1:7788 for 7h19m after the
// round that started it moved on, and nothing in this repo noticed. The runner is the fix: refuse to
// start when the port is taken and NAME the holder, and prove the port is free after stopping.
//
// The behavioural half is the point. A mock would agree with whatever the code does, so these cases
// start real listeners and real child processes, and the detector is given a negative control: a
// listener nobody claimed MUST make it fail, or "the port is free" is a sentence that cannot be false.
import { spawn } from 'node:child_process';
import { createServer } from 'node:net';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  LOCK_DIR, ROOT, assertNoListener, assertPortFree, listLocks, lockPath, pidAlive, probePort,
  startConsole, stopAndVerify,
} from '../tools/console-runner.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const TMP = join(resolve(HERE, '..'), '.tmp');
const FIXTURE = join(TMP, 'console-hygiene-fixture.mjs');

let pass = 0;
let fail = 0;
function check(name, ok, detail = '') {
  if (ok) { pass++; console.log(`  ok   ${name}${detail ? ' -- ' + detail : ''}`); }
  else { fail++; console.log(`  FAIL ${name}${detail ? ' -- ' + detail : ''}`); }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** A port nothing is using: bind :0, read the port, close. Never hardcode -- a fixed port is how a
 *  test collides with a real console or with a previous run of itself. */
async function freePort() {
  const srv = createServer();
  await new Promise((r) => srv.listen(0, '127.0.0.1', r));
  const { port } = srv.address();
  await new Promise((r) => srv.close(r));
  return port;
}

/** Poll instead of assuming. A child that has PRINTED its token has not necessarily finished binding:
 *  the first version of this test asserted the port in the same tick the token arrived and failed on a
 *  correct implementation. An assertion that cannot be satisfied is worse than no assertion. */
async function waitForPort(port, want, timeoutMs = 2500) {
  const t0 = Date.now();
  for (;;) {
    if ((await probePort(port)) === want) return true;
    if (Date.now() - t0 > timeoutMs) return false;
    await sleep(100);
  }
}

/** Rejection must be a refusal, not a crash later: returns the message or null. */
async function refusal(fn) {
  try { await fn(); return null; } catch (err) { return err.message; }
}

mkdirSync(TMP, { recursive: true });
writeFileSync(FIXTURE, `// generated by test/console-hygiene.test.mjs -- a stand-in console
const port = Number(process.argv[process.argv.indexOf('--port') + 1]);
if (process.argv.includes('--listen')) {
  const { createServer } = await import('node:net');
  createServer(() => {}).listen(port, '127.0.0.1');
}
console.log('console: http://127.0.0.1:' + port + '/?t=FIXTUREtoken123456789');
setInterval(() => {}, 1000);
`, 'utf8');

// --- 1. the probe tells the truth about an empty port and an occupied one ------------------------
{
  const p = await freePort();
  check('an unused port reads as free', (await probePort(p)) === false, `port ${p}`);
  const srv = createServer();
  await new Promise((r) => srv.listen(p, '127.0.0.1', r));
  check('a listening port reads as occupied', (await probePort(p)) === true, `port ${p}`);
  const why = await refusal(() => assertPortFree(p, { tool: 'console-hygiene-test' }));
  check('assertPortFree REFUSES an unowned listener instead of racing it',
    why !== null && /SERVING/.test(why) && /no lock file/.test(why), why ? why.slice(0, 120) : 'it resolved');
  await new Promise((r) => srv.close(r));
  await sleep(50);
  check('the port reads free again after the listener closes', (await probePort(p)) === false);
}

// --- 2. the lock attributes a holder, and a dead pid is debris rather than a claim --------------
{
  const p = await freePort();
  mkdirSync(LOCK_DIR, { recursive: true });
  writeFileSync(lockPath(p), JSON.stringify({
    pid: process.pid, port: p, tool: 'ghost-tool', app: 'x.mjs', startedAt: new Date().toISOString(),
  }));
  const why = await refusal(() => assertPortFree(p, { tool: 'console-hygiene-test' }));
  check('a lock owned by a LIVE pid refuses the port and names the tool',
    why !== null && /held by a live console/.test(why) && /ghost-tool/.test(why), why ? why.slice(0, 140) : 'it resolved');
  check('pidAlive() is the liveness probe this rests on', pidAlive(process.pid) === true && pidAlive(999999) === false);
  writeFileSync(lockPath(p), JSON.stringify({
    pid: 999999, port: p, tool: 'dead-tool', app: 'x.mjs', startedAt: new Date().toISOString(),
  }));
  await assertPortFree(p, { tool: 'console-hygiene-test' });
  check('a lock whose pid is DEAD does not block, and is cleared as debris', !existsSync(lockPath(p)));
}

// --- 3. start + stop, on a real child, with the proof ------------------------------------------
{
  const p = await freePort();
  const h = await startConsole({ app: FIXTURE, port: p, args: ['--listen'], tool: 'console-hygiene-test' });
  check('startConsole returns the token the console printed',
    h.token === 'FIXTUREtoken123456789', String(h.token).slice(0, 24));
  check('startConsole wrote a lock naming the tool and the live pid',
    existsSync(lockPath(p)) && JSON.parse(readFileSync(lockPath(p), 'utf8')).tool === 'console-hygiene-test');
  check('the console is really up (its port answers)', (await waitForPort(p, true)) === true, `port ${p}`);
  await stopAndVerify(h);
  check('after stopAndVerify the lock is gone', !existsSync(lockPath(p)));
  check('after stopAndVerify the port is released', (await waitForPort(p, false)) === true);
  check('stopConsole is idempotent (a second call is not an error)', (await stopAndVerify(h)) === true);
}

// --- 4. the pre-flight refuses to start on an occupied port, and leaves no lock -----------------
{
  const p = await freePort();
  const squat = createServer();
  await new Promise((r) => squat.listen(p, '127.0.0.1', r));
  const why = await refusal(() => startConsole({ app: FIXTURE, port: p, tool: 'console-hygiene-test' }));
  check('startConsole refuses to spawn onto an occupied port', why !== null && /SERVING/.test(why),
    why ? why.slice(0, 120) : 'it spawned');
  check('a refused start leaves no lock behind', !existsSync(lockPath(p)));
  await new Promise((r) => squat.close(r));
}

// --- 5. NEGATIVE CONTROL: the leak detector must fail on a listener nobody claimed --------------
{
  const p = await freePort();
  const bare = spawn(process.execPath, [FIXTURE, '--port', String(p), '--listen'], { stdio: 'ignore' });
  check('the bare listener is up (so the control is real)', (await waitForPort(p, true)) === true, `port ${p}`);
  const why = await refusal(() => assertNoListener(p, 'console-hygiene-test'));
  check('★ assertNoListener FAILS on a listener that outlived its run', why !== null && /STILL serving/.test(why),
    why ? why.slice(0, 120) : 'it passed, which would make the whole contract decorative');
  try { bare.kill(); } catch { /* already gone */ }
  check('and it passes once the listener is really gone', (await waitForPort(p, false)) === true);
}

// --- 6. the census: every tool that boots a console is either converted or declared -------------
{
  // A console booter is a file that either spawns the console ITSELF (debt: it owns the lifecycle by
  // hand) or calls the runner's startConsole (converted). The first version of this census only looked
  // for the spawn form, so converting a tool made it INVISIBLE to the guard that watches conversions --
  // the check below caught that, which is why the rule now covers both halves.
  const BOOTS = /(?:spawn|spawnSync)\s*\([\s\S]{0,200}?(?:app\.mjs|\bAPP\b|\bCONSOLE\b)|startConsole\s*\(/;
  const detected = readdirSync(join(ROOT, 'tools'))
    .filter((f) => f.endsWith('.mjs') && f !== 'console-runner.mjs')
    .filter((f) => {
      const src = readFileSync(join(ROOT, 'tools', f), 'utf8');
      return src.includes('app.mjs') && BOOTS.test(src);
    })
    .map((f) => 'tools/' + f)
    .sort();

  // Converted: every tool listed below takes the lock, pre-flights the port BY NAME, and can prove
  // the release. The list is the inventory -- do not re-count it in prose elsewhere.
  const USES_RUNNER = ['tools/admission-ceremony.mjs', 'tools/ceremony-live-trial.mjs', 'tools/deploy-stick.mjs',
    'tools/relay-actions-live.mjs', 'tools/binding-live-probe.mjs', 'tools/console-relay-trial.mjs',
    'tools/permit-seam-probe.mjs', 'tools/bridge-trial.mjs'];
  // Declared debt, each with the reason it is not converted yet. Not a compliment -- a census entry.
  // EMPTY as of 2026-10-12: every console booter in tools/ now takes the lock, pre-flights the port by
  // NAME and can prove the release. The map is kept because the rule is "converted or declared": a
  // newly added booter must land in one of the two lists, and in neither is a FAILURE below.
  const DEBT = new Map([]);

  for (const f of detected) {
    const src = readFileSync(join(ROOT, f), 'utf8');
    const converts = USES_RUNNER.includes(f);
    const declared = DEBT.has(f);
    check(`console booter '${f}' is either converted or declared`, converts || declared,
      converts ? 'uses tools/console-runner.mjs' : declared ? DEBT.get(f) : 'NEITHER: a new unguarded console booter');
    if (converts) check(`converted booter '${f}' really imports the runner`, src.includes('console-runner'));
  }
  for (const f of USES_RUNNER) {
    check(`runner user '${f}' is still a console booter (no stale census entry)`, detected.includes(f));
  }
  for (const f of DEBT.keys()) {
    check(`declared-debt entry '${f}' still exists and still boots a console`, detected.includes(f));
  }
  check('the census found consoles to audit', detected.length >= 8, `${detected.length}: ${detected.join(', ')}`);
}

// --- 7. no file may shadow the global console object ---------------------------------------------
{
  // Measured 2026-10-12: renaming a console handle to \`console\` shadowed the global object, so every
  // console.log ABOVE the declaration threw "Cannot access 'console' before initialization" at MODULE
  // LOAD -- in the two tools this chain cannot execute, because they need the stick and they write. A
  // static name rule is the only cheap guard this suite can offer for them, and node --check cannot see
  // it (the syntax is fine; the semantics are not).
  const SHADOW = /(?:const|let|var)\s+console\s*=/;
  // Assembled at run time ON PURPOSE: written as a literal, this file would match its own rule -- the
  // same self-match that made an earlier guard (queue-producer-convention) report itself.
  const forbidden = ['const', 'console', '=', 'null;'].join(' ');
  check('the shadow rule matches the shape it forbids (control)', SHADOW.test(forbidden));
  const offenders = [];
  for (const dir of ['tools', 'test']) {
    for (const f of readdirSync(join(ROOT, dir)).filter((x) => x.endsWith('.mjs'))) {
      if (SHADOW.test(readFileSync(join(ROOT, dir, f), 'utf8'))) offenders.push(dir + '/' + f);
    }
  }
  check('no file shadows the global console object', offenders.length === 0, offenders.join(', ') || 'none');
}

// --- cleanup -----------------------------------------------------------------------------------
rmSync(FIXTURE, { force: true });
for (const l of listLocks()) {
  if (l && l.port) rmSync(lockPath(l.port), { force: true });
}

console.log('');
console.log(`console-hygiene: ${pass} passed, ${fail} failed`);
if (fail > 0) process.exit(1);
console.log('CONSOLE HYGIENE OK: a squatter is refused by name, and every stop is proven against the port.');
