/**
 * Separate TRIAL DEBRIS from a REAL APPLICANT in the relay's admission queue.
 *
 * WHY THIS IS A SHARED MODULE. It used to live inside tools/admission-queue-review.mjs, which made
 * the convention a property of one command-line tool. The console needs the same judgement -- it is
 * the human admin's only interface, and an applicant that the console cannot classify is an
 * applicant the console cannot show -- and two copies of one convention drift. The drift here is
 * not cosmetic: if the console's copy is the more suspicious one, a real applicant is labelled
 * debris and silently never admitted.
 *
 * WHY IT MATTERS. The console's admission review is the human admin's job: look at who is waiting,
 * decide. It is not usable if the queue is full of the test harness's own leavings and nothing marks
 * them as such. The failure is asymmetric and that is the whole design principle here: showing a
 * trial entry as a possible applicant costs a human ten seconds of reading, while showing a REAL
 * applicant as trial debris means the applicant is silently never admitted. So the classifier fails
 * toward the human, never away from them.
 *
 * THE CONVENTION, going forward: a request generated by a trial MUST carry a note beginning
 * `[trial]`. The legacy labels below predate the convention and are listed explicitly so the
 * existing debris stays recognisable. Anything else -- including an empty note -- is REAL, i.e.
 * "a human should look at this".
 *
 * THE KNOWN LIMIT, stated rather than glossed: a real applicant who sets their note to exactly
 * "joiner-path-trial" would be misclassified as debris. That is a deliberate trade: the legacy
 * list is fixed and documented, the strings are meaningless outside this repository, and the
 * alternative (guessing) is worse.
 */

/**
 * The labels this repository's own tools have written into real requests. Every one of these was
 * observed in the live queue on 2026-10-12. Kept as data, not as a regex, so it can be audited.
 */
export const LEGACY_TRIAL_NOTES = [
  'joiner-path-trial',
  'console bridge trial',
  'operator-command-trial',
  'live remote trial',
  'vendor gate trial',
];

export const TRIAL = 'trial';
export const REAL = 'real';

/**
 * Classify one queue entry.
 *
 * @returns {{kind: string, why: string}}
 */
export function classifyNote(note) {
  if (typeof note === 'string' && /^\s*\[trial\]/i.test(note)) {
    return { kind: TRIAL, why: 'carries the [trial] marker' };
  }
  if (typeof note === 'string' && LEGACY_TRIAL_NOTES.includes(note.trim())) {
    return { kind: TRIAL, why: 'matches a documented legacy trial label' };
  }
  if (typeof note !== 'string' || note.trim() === '') {
    // NO NOTE AT ALL is the single most applicant-like thing an entry can look like: a real
    // joiner following the door's instructions has no reason to fill in a note for us.
    return { kind: REAL, why: 'no note -- a human should look at this' };
  }
  return { kind: REAL, why: 'note does not match any trial marker' };
}

/** Whole-queue verdict, so an unreachable or empty queue cannot be confused with a clean one. */
export function triage(requests) {
  const rows = (requests ?? []).map((r) => ({ ...r, ...classifyNote(r.note) }));
  return {
    rows,
    trials: rows.filter((r) => r.kind === TRIAL),
    real: rows.filter((r) => r.kind === REAL),
  };
}
